// Packs public/ into a single Cloudflare Pages "advanced mode" _worker.js (all files embedded).
// Why: deploying this way needs only the API token (the normal asset-upload step uses a
// separate short-lived JWT that some proxies overwrite). Output: dist/_worker.js
// Usage: node scripts/build-worker.mjs   then   wrangler pages deploy dist --project-name tggc2569-register
import { readFileSync, readdirSync, statSync, mkdirSync, writeFileSync, rmSync } from "node:fs";
import { join, relative, extname } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const pub = join(root, "public");
const TYPES = {
  ".html": "text/html; charset=utf-8", ".css": "text/css; charset=utf-8", ".js": "text/javascript; charset=utf-8",
  ".png": "image/png", ".svg": "image/svg+xml", ".json": "application/json", ".txt": "text/plain; charset=utf-8", ".ico": "image/x-icon",
};
const SKIP = new Set(["_headers", "_redirects"]);
const files = {};
(function walk(dir) {
  for (const n of readdirSync(dir)) {
    const p = join(dir, n);
    if (statSync(p).isDirectory()) { walk(p); continue; }
    const rel = "/" + relative(pub, p).split("\\").join("/");
    if (SKIP.has(n) || !TYPES[extname(n)]) continue;
    const bin = extname(n) === ".png" || extname(n) === ".ico";
    files[rel] = { t: TYPES[extname(n)], b: bin ? readFileSync(p).toString("base64") : readFileSync(p, "utf8"), bin };
  }
})(pub);

const src = `// generated by scripts/build-worker.mjs — do not edit
const FILES = ${JSON.stringify(files)};
const BIN = {};
function body(f, k) {
  if (!f.bin) return f.b;
  if (!BIN[k]) { const s = atob(f.b); const u = new Uint8Array(s.length); for (let i = 0; i < s.length; i++) u[i] = s.charCodeAt(i); BIN[k] = u; }
  return BIN[k];
}
export default {
  async fetch(req) {
    const url = new URL(req.url);
    let p = decodeURIComponent(url.pathname);
    if (p === "/staff") return Response.redirect(url.origin + "/staff/" + url.search, 301);
    if (p.endsWith("/")) p += "index.html";
    if (p.endsWith("/index")) p += ".html";
    const f = FILES[p];
    if (!f || (req.method !== "GET" && req.method !== "HEAD")) {
      return new Response("ไม่พบหน้านี้ · Not found", { status: f ? 405 : 404, headers: { "content-type": "text/plain; charset=utf-8" } });
    }
    const h = new Headers({
      "content-type": f.t,
      "x-content-type-options": "nosniff",
      "referrer-policy": "strict-origin-when-cross-origin",
      "cache-control": f.t.startsWith("text/html") || p === "/config.js" || p.startsWith("/staff/") ? "no-cache" : "public, max-age=3600",
    });
    if (p.startsWith("/staff/")) { h.set("x-robots-tag", "noindex, nofollow"); h.set("permissions-policy", "camera=(self)"); }
    return new Response(req.method === "HEAD" ? null : body(f, p), { headers: h });
  },
};
`;
const out = join(root, "dist");
rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
writeFileSync(join(out, "_worker.js"), src);
console.log("dist/_worker.js", Object.keys(files).length, "files,", Math.round(src.length / 1024), "KB");
